import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type * as Bytenode from 'bytenode';
import { electronBinary, packageDir } from './stage';

/**
 * Compiles the staged main process (`blacklight-main.cjs`) to V8 bytecode (SEC-04) with bytenode,
 * inside a real Electron main process of the version that ships (bytecode is tied to the exact V8
 * build, L5), and replaces the source. `main.cjs` becomes a loader.
 *
 * The page's code cannot be bytecode: loading bytecode needs Node in the renderer, which the
 * sandbox forbids. It is obfuscated instead (SEC-03).
 *
 * @example
 * ```ts
 * import { compileMainToBytecode, stageApp } from '@blacklight/native/build';
 *
 * stageApp({ appDir, manifest, webDist: 'dist' });
 * await compileMainToBytecode(appDir);
 * ```
 */
export async function compileMainToBytecode(
  appDir: string,
  electron = electronBinary(),
): Promise<void> {
  // bytenode is CommonJS: its functions sit on the default export when imported from ESM.
  const loaded = (await import('bytenode')) as typeof Bytenode & { default?: typeof Bytenode };
  const { compileFile } = loaded.default ?? loaded;
  const source = join(appDir, 'blacklight-main.cjs');
  await compileFile({
    filename: source,
    output: join(appDir, 'blacklight-main.jsc'),
    electronMain: true,
    electronPath: electron,
    compileAsModule: true,
    createLoader: false,
  });
  rmSync(source);
  rmSync(`${source}.map`, { force: true });
  const runtime = join(appDir, 'native_modules', 'bytenode');
  mkdirSync(runtime, { recursive: true });
  cpSync(packageDir('bytenode'), runtime, {
    recursive: true,
    dereference: true,
    filter: (src) => !/[/\\]node_modules([/\\]|$)/.test(src.slice(packageDir('bytenode').length)),
  });
  writeFileSync(
    join(appDir, 'main.cjs'),
    "// Generated by the blacklight CLI: the main process is V8 bytecode.\nrequire('./native_modules/bytenode');\nrequire('./blacklight-main.jsc').startApp({ appDir: __dirname });\n",
  );
}
