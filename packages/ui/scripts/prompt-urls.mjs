// Writes src/prompt-urls.js: one `new URL()` per Kenney glyph in prompts/. Kept out of the library
// bundle (Vite would inline every SVG); the game's bundler emits only the files it references.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../prompts/', import.meta.url));
const lines = [];
for (const family of readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()) {
  for (const file of readdirSync(root + family)
    .filter((f) => f.endsWith('.svg'))
    .sort()) {
    const key = `${family}/${file.slice(0, -4)}`;
    lines.push(
      `  ${JSON.stringify(key)}: () => new URL(${JSON.stringify(`../prompts/${family}/${file}`)}, import.meta.url).href,`,
    );
  }
}
const out = fileURLToPath(new URL('../src/prompt-urls.js', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/prompt-urls.mjs. Do not edit.\nexport const promptUrls = {\n${lines.join('\n')}\n};\n`,
);
writeFileSync(
  out.replace(/\.js$/, '.d.ts'),
  '// Generated by scripts/prompt-urls.mjs.\nexport declare const promptUrls: Record<string, () => string>;\n',
);
console.log(`${lines.length} prompt glyphs`);
