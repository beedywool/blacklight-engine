import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';
import vue from '@vitejs/plugin-vue';
import { searchForWorkspaceRoot, type InlineConfig, type Plugin, type ViteDevServer } from 'vite';
import { buildAtlases, pngSize } from './atlas';
import { fontSubsetting } from './fonts';
import { ink } from './ink';
import { loadGameConfig, scanAssets, typesFile } from './project';

/** Import aliases available in every game (SPEC §6.1). */
export const PROJECT_ALIASES = {
  '@objects': 'objects',
  '@ui': 'ui',
  '@modules': 'modules',
  '@assets': 'assets',
  '@models': 'models',
  '@stories': 'stories',
} as const;

/** Folder, inside the game, where the CLI writes the files Vite needs. Ignored by git. */
export const GENERATED_DIR = '.blacklight';

const ASSETS_ID = 'virtual:blacklight/assets';
const RESOLVED_ASSETS_ID = `\0${ASSETS_ID}`;

/** Loose images up to this size are packed into atlases in release builds. */
const MAX_PACKED = 1024;

const CONFIG_FILES = ['game.config.ts', 'game.config.js'];

const INDEX_HTML = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <title>Blacklight</title>
    <style>
      html, body { margin: 0; height: 100%; background: #000; }
      #game { width: 100vw; height: 100vh; height: 100dvh; }
    </style>
  </head>
  <body>
    <div id="game"></div>
    <script type="module" src="./main.ts"></script>
  </body>
</html>
`;

const mainTs = (
  withUi: boolean,
) => `// Generated by the blacklight CLI and rewritten on every run: do not edit.
import { createGame, objectsFromGlob, scenesFromGlob } from '@blacklight/core';${
  withUi ? "\nimport { ui } from '@blacklight/ui';\nimport '@blacklight/ui/style.css';" : ''
}
import assets from '${ASSETS_ID}';
import config from '../game.config';

const mount = document.getElementById('game')!;

function fail(error: unknown): never {
  const box = document.createElement('pre');
  box.style.cssText = 'margin:0;padding:24px;color:#f2b8b5;background:#080808;font:14px/1.5 ui-monospace,monospace;white-space:pre-wrap;height:100%;box-sizing:border-box';
  box.textContent = error instanceof Error ? error.message : String(error);
  mount.replaceChildren(box);
  throw error;
}

try {
  const scenes = scenesFromGlob(import.meta.glob('../scenes/*/*.scene.{ts,js}'));
  const objects = objectsFromGlob(
    import.meta.glob(['../objects/*/*.object.{ts,js}', '../scenes/*/objects/*/*.object.{ts,js}']),
  );
  const plugins = [${
    withUi ? "ui({ screens: import.meta.glob(['../ui/**/*.vue', '../scenes/*/ui/**/*.vue']) })" : ''
  }];
  const game = await createGame(config, { scenes, objects, assets, mount, plugins });
  if (import.meta.env.DEV) {
    // Console and test access in dev: the running game and the engine module itself.
    Object.assign(window, { blacklight: game, blacklightCore: await import('@blacklight/core') });
    const { installDebug } = await import('@blacklight/core/debug');
    installDebug(game);${
      withUi
        ? "\n    const { installInspector } = await import('@blacklight/ui/inspector');\n    installInspector(game);"
        : ''
    }
  }
} catch (error) {
  fail(error);
}
`;

function writeIfChanged(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
}

/**
 * Checks that `root` is a game and writes the generated entry files.
 *
 * @returns The generated folder, used as Vite's root.
 * @throws Error when `root` has no `game.config.ts`.
 */
export function prepareProject(root: string): string {
  if (!CONFIG_FILES.some((file) => existsSync(join(root, file)))) {
    throw new Error(
      `No game.config.ts in ${root}. Run the command from your game's folder, or create a game with \`pnpm create blacklight\`.`,
    );
  }
  const dir = join(root, GENERATED_DIR);
  mkdirSync(dir, { recursive: true });
  writeIfChanged(join(dir, 'index.html'), INDEX_HTML);
  writeIfChanged(join(dir, 'main.ts'), mainTs(usesUi(root)));
  writeIfChanged(join(dir, '.gitignore'), '*\n');
  return dir;
}

/** `true` when the game depends on `@blacklight/ui` (Vue screens). */
export function usesUi(root: string): boolean {
  try {
    const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
      dependencies?: Record<string, string>;
      devDependencies?: Record<string, string>;
    };
    return '@blacklight/ui' in { ...manifest.dependencies, ...manifest.devDependencies };
  } catch {
    return false;
  }
}

/**
 * Validates `game.config.ts` and writes `.blacklight/types.d.ts` with the game's scene, object,
 * action, animation and asset names.
 *
 * @throws Error listing every invalid configuration field.
 */
export async function generateTypes(root: string): Promise<void> {
  const config = await loadGameConfig(root);
  const actions = Object.keys(config.input?.actions ?? {});
  mkdirSync(join(root, GENERATED_DIR), { recursive: true });
  writeIfChanged(join(root, GENERATED_DIR, 'types.d.ts'), typesFile(root, actions));
}

/**
 * Folders the dev server may read: the game, plus the workspaces of linked engine packages
 * (`link:` installs while developing the engine resolve outside the game).
 */
function allowedFolders(root: string): string[] {
  const folders = new Set([root, searchForWorkspaceRoot(root)]);
  const scope = join(root, 'node_modules', '@blacklight');
  if (existsSync(scope)) {
    for (const name of readdirSync(scope))
      folders.add(searchForWorkspaceRoot(realpathSync(join(scope, name))));
  }
  return [...folders];
}

/** Manifest module: every asset by project path, and atlases in release builds. */
export function manifestModule(
  root: string,
  emit?: (name: string, source: Buffer) => string,
): string {
  const files = scanAssets(root);
  const imports: string[] = [];
  const entries: string[] = [];
  const atlasEntries: string[] = [];
  let packed = new Set<string>();
  if (emit) {
    const candidates = files
      .filter((f) => f.endsWith('.png'))
      .map((id) => ({ id, data: readFileSync(join(root, id)) }))
      .filter(({ data }) => {
        const size = pngSize(data);
        return !!size && size.width <= MAX_PACKED && size.height <= MAX_PACKED;
      });
    if (candidates.length > 1) {
      const { pages, frames } = buildAtlases(candidates);
      const refs = pages.map((page, i) => emit(`atlas-${i}.png`, page));
      for (const [id, { page, frame }] of frames) {
        atlasEntries.push(
          `    ${JSON.stringify(id)}: { url: import.meta.ROLLUP_FILE_URL_${refs[page]}, frame: ${JSON.stringify(frame)} },`,
        );
      }
      packed = new Set(frames.keys());
    }
  }
  files.forEach((file, i) => {
    if (packed.has(file)) return;
    imports.push(`import a${i} from ${JSON.stringify(`${join(root, file)}?url`)};`);
    entries.push(`    ${JSON.stringify(file)}: a${i},`);
  });
  return `${imports.join('\n')}
export default {
  files: {
${entries.join('\n')}
  },
  atlases: {
${atlasEntries.join('\n')}
  },
};
`;
}

/** Vite plugin with the game conventions: aliases, asset manifest, atlases, generated types. */
export function blacklight(options: { root: string }): Plugin {
  const root = resolve(options.root);
  let build = false;
  let server: ViteDevServer | undefined;
  let timer: NodeJS.Timeout | undefined;

  const refresh = () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      generateTypes(root).catch((error: unknown) =>
        server?.config.logger.error(error instanceof Error ? error.message : String(error)),
      );
      const module = server?.moduleGraph.getModuleById(RESOLVED_ASSETS_ID);
      if (module) server!.moduleGraph.invalidateModule(module);
      server?.ws.send({ type: 'full-reload' });
    }, 100);
  };

  return {
    name: 'blacklight',
    config(_, env) {
      build = env.command === 'build';
      return {
        resolve: {
          alias: Object.entries(PROJECT_ALIASES).map(([find, dir]) => ({
            find,
            replacement: join(root, dir),
          })),
        },
        server: { fs: { allow: allowedFolders(root) } },
      };
    },
    async buildStart() {
      await generateTypes(root);
    },
    configureServer(dev) {
      server = dev;
      dev.watcher.add(root);
      const onListChange = (file: string) => {
        if (file.includes(`/${GENERATED_DIR}/`) || file.includes('/node_modules/')) return;
        refresh();
      };
      dev.watcher.on('add', onListChange);
      dev.watcher.on('unlink', onListChange);
      dev.watcher.on('change', (file) => {
        if (/\.(anim|aseprite)\.json$|game\.config\.[jt]s$/.test(file)) refresh();
      });
    },
    resolveId(id) {
      return id === ASSETS_ID ? RESOLVED_ASSETS_ID : undefined;
    },
    load(id) {
      if (id !== RESOLVED_ASSETS_ID) return undefined;
      return manifestModule(
        root,
        build ? (name, source) => this.emitFile({ type: 'asset', name, source }) : undefined,
      );
    },
  };
}

export interface ViteConfigOptions {
  port?: number;
  host?: string | boolean;
  open?: boolean;
  strictPort?: boolean;
}

/** Full Vite configuration for a game; the CLI passes it to Vite's `createServer` / `build`. */
export function createViteConfig(gameRoot: string, options: ViteConfigOptions = {}): InlineConfig {
  const root = resolve(gameRoot);
  const generated = prepareProject(root);
  return {
    configFile: false,
    root: generated,
    // Relative URLs: the same build runs from a web server, a custom protocol (Electron) or a WebView.
    base: './',
    publicDir: join(root, 'public'),
    envDir: root,
    cacheDir: join(root, 'node_modules', '.vite'),
    plugins: [blacklight({ root }), vue(), ink(), fontSubsetting({ root })],
    resolve: {
      // One copy of each, even when engine packages are linked from a checkout.
      dedupe: ['vue', 'pixi.js', 'motion', '@blacklight/core', '@blacklight/ui'],
    },
    // The UI package references its glyph files with `new URL(..., import.meta.url)`, which
    // pre-bundling would break.
    optimizeDeps: { exclude: ['@blacklight/ui'] },
    server: {
      port: options.port,
      host: options.host,
      open: options.open,
      strictPort: options.strictPort,
    },
    preview: { port: options.port, host: options.host },
    build: {
      outDir: join(root, 'dist'),
      emptyOutDir: true,
      target: 'es2023',
      // Assets stay files: the engine loads them by URL (and offline caches can list them).
      assetsInlineLimit: 0,
    },
  };
}
