// Refreshes src/input/gamecontrollerdb.ts from SDL_GameControllerDB (zlib license).
// Run with `pnpm --filter @blacklight/core update:gamepads`; commit the result.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE =
  'https://raw.githubusercontent.com/mdqinc/SDL_GameControllerDB/master/gamecontrollerdb.txt';
const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE}: HTTP ${response.status}`);
const lines = (await response.text())
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'));
const out = fileURLToPath(new URL('../src/input/gamecontrollerdb.ts', import.meta.url));
writeFileSync(
  out,
  `// Generated by scripts/update-gamecontrollerdb.js on ${new Date().toISOString().slice(0, 10)} from\n` +
    `// ${SOURCE} (zlib license). Do not edit.\n` +
    `export const GAME_CONTROLLER_DB = ${JSON.stringify(lines.join('\n'))};\n`,
);
console.log(`${lines.length} mappings written to ${out}`);
