export interface CreateGameOptions {
  /** Scene loaders by name, usually from `scenesFromGlob(import.meta.glob(...))`. */
  scenes: Record<string, SceneLoader>;
  /** Object classes from `objectsFromGlob(import.meta.glob(...))`. */
  objects?: ObjectRegistry;
  /** Asset manifest generated by the CLI. */
  assets?: AssetManifest;
  /** Element the game fills. */
  mount: HTMLElement;
  /** Set up before the first scene starts (`@blacklight/ui` installs its layer this way). */
  plugins?: ((game: Game) => void | Promise<void>)[];
  /** Release build: encrypted saves and the `security` measures (the CLI passes it). */
  release?: boolean;
  /** Modules from `game.config.ts`, set up after the plugins (the CLI generates the list). */
  modules?: ModuleList;
}

/**
 * What `@blacklight/ui` provides to scenes as `this.ui`. Core only knows the shape; screens are
 * Vue components, typed `unknown` here.
 */
export interface SceneUi {
  /** Shows a screen over the others (HUD). */
  open(
    screen: unknown,
    props?: Record<string, unknown>,
    options?: Record<string, unknown>,
  ): UiScreenHandle;
  /** Shows a screen and hides the ones below until it closes (menus). */
  push(
    screen: unknown,
    props?: Record<string, unknown>,
    options?: Record<string, unknown>,
  ): UiScreenHandle;
  /** Shows a modal screen and resolves with its result. */
  modal(
    screen: unknown,
    props?: Record<string, unknown>,
    options?: Record<string, unknown>,
  ): Promise<unknown>;
  /** Asks a yes/no question. */
  confirm(options: {
    title?: string;
    message: string;
    confirm?: string;
    cancel?: string;
    danger?: boolean;
  }): Promise<boolean>;
  /** Closes the top menu of this owner. */
  pop(result?: unknown): void;
  replace(
    screen: unknown,
    props?: Record<string, unknown>,
    options?: Record<string, unknown>,
  ): UiScreenHandle;
  closeAll(): void;
}

/** An open screen, as `SceneUi` returns it. */
export interface UiScreenHandle {
  readonly id: number;
  close(result?: unknown): void;
  readonly result: Promise<unknown>;
}

/** A UI layer installed on the game (`@blacklight/ui`). */
export interface UiHost {
  /** Screens that belong to `scene` and close with it. */
  forScene(scene: Scene<never>): SceneUi;
  /** Called when a scene stops. */
  sceneEnded(scene: Scene<never>): void;
}

/** A scene change effect. `progress` goes 0 → 1 while covering, then 1 → 0 while revealing. */
export interface Transition {
  /** Duration of each half in ms (real time). */
  duration: number;
  draw(layer: PixiContainer, progress: number, size: { width: number; height: number }): void;
}

export interface GotoOptions {
  /**
   * `'none'`, `'fade'` (black), a name registered in `game.transitions` (`@blacklight/ui` adds
   * `wipe`, `iris`, `ink`, `slices`, `shatter`, `zoom`…), or a transition object.
   * @defaultValue `'none'`
   */
  transition?: 'fade' | 'none' | (string & {}) | Transition;
}

export interface GameEvents {
  /** A scene started. */
  scene: { name: string };
  pause: void;
  resume: void;
  /** Loading progress of the scene being loaded, 0–1. */
  loading: { scene: string; progress: number };
  /** Every fixed step, after the scenes. */
  step: { step: number };
  /** The screen size or the viewport changed. */
  resize: { viewport: Viewport };
  /** Every displayed frame, paused or not (UI layers animate with it). */
  frame: { deltaMS: number };
  /** Tampering detected (release builds): a listener replaces the default restore + log. */
  tamper: TamperEvent;
}

/** Game time, advanced by the fixed step. */
export interface GameTime {
  /** Fixed steps since the start. */
  step: number;
  /** Game time in ms (stops while paused, follows `scale`). */
  now: number;
  /** Seconds per step: `1 / tickRate`. */
  readonly dt: number;
  /** Speed of the game clock: 0.5 is slow motion. */
  scale: number;
}

/** What shows while a scene's code and files load. Assign `game.loadingScreen` to replace it. */
export interface LoadingScreen {
  /** Draws progress (0–1) into `layer`, which covers the design area and is cleared afterwards. */
  draw(layer: PixiContainer, progress: number, size: { width: number; height: number }): void;
}

/** Default loading screen: a thin white bar near the bottom. */
export const BAR_LOADING_SCREEN: LoadingScreen = {
  draw(layer, progress, { width, height }) {
    let bar = layer.children[0] as PixiGraphics | undefined;
    if (!bar) bar = layer.addChild(new PixiGraphics());
    bar
      .clear()
      .rect(width * 0.3, height * 0.9, width * 0.4, 4)
      .fill({ color: 0x3a3a3a })
      .rect(width * 0.3, height * 0.9, width * 0.4 * progress, 4)
      .fill({ color: 0xffffff });
  },
};

const FADE: Transition = {
  duration: 250,
  draw(layer, progress, size) {
    let cover = layer.children[0] as PixiGraphics | undefined;
    if (!cover) {
      cover = new PixiGraphics();
      layer.addChild(cover);
    }
    cover
      .clear()
      .rect(-size.width, -size.height, size.width * 3, size.height * 3)
      .fill({ color: 0x000000, alpha: progress });
  },
};

/**
 * The running game: owns the renderer, the fixed-step loop, input, audio, assets and the scenes.
 * Created by {@link createGame}; scenes and objects reach it through `this.game`.
 */
export class Game {
  readonly config: ResolvedGameConfig;
  readonly app = new Application();
  /** Holds the scenes, scaled and offset to the viewport. */
  readonly world = new PixiContainer();
  readonly events = new EventBus<GameEvents>();
  readonly settings: Settings;
  readonly assets: AssetStore;
  readonly sheets: SheetCache;
  readonly input: InputManager;
  readonly audio: AudioManager;
  /** Game-wide seeded random generator (`config.seed`). */
  readonly random: Random;
  readonly time: GameTime;
  viewport!: Viewport;
  /** Current scene, `undefined` while the first scene loads. */
  scene: Scene<never> | undefined;
  /** Scenes opened over the current one, bottom first. */
  readonly overlays: { scene: Scene<never>; pauseBelow: boolean }[] = [];
  /** Device pixels per virtual pixel; text renders at this resolution. */
  textResolution = 1;
  /** `true` while paused by `pause()` (not by losing focus). */
  paused = false;
  /**
   * Platform services (files, save key, native calls). The web platform unless a platform package
   * replaces it from a plugin, before the first scene starts.
   */
  platform: Platform;
  /** UI layer, installed by `@blacklight/ui`. */
  ui: UiHost | undefined;
  /** APIs of the modules listed in `game.config.ts`, by name (`game.modules.sqlite`). */
  get modules(): GameModules {
    return (this.moduleHost?.apis ?? {}) as GameModules;
  }
  /** Scene transitions by name, usable as `goto(name, params, { transition: 'fade' })`. */
  readonly transitions = new Map<string, Transition>([['fade', FADE]]);
  /** Drawn while scenes load; replace it to show your own art. */
  loadingScreen: LoadingScreen = BAR_LOADING_SCREEN;
  /**
   * Part of the screen not covered by notches, rounded corners or system bars, in virtual pixels
   * of the design area. Anchor HUD elements inside it.
   */
  safeArea: Rect = { x: 0, y: 0, width: 0, height: 0 };
  /** `true` in release builds (`blacklight build`), `false` with `blacklight dev`. */
  readonly release: boolean;
  /** Save slots and the current save data. */
  readonly save: SaveManager;
  /** Release-build hardening (protected values, debugger detection, tamper reaction). */
  readonly security: SecurityRuntime;

  private readonly scenes: Record<string, SceneLoader>;
  private readonly registry: ObjectRegistry;
  private readonly classes = new Map<string, typeof GameObject>();
  private readonly sceneClasses = new Map<string, Map<string, typeof GameObject>>();
  /** Element the game fills; UI layers add themselves to it. */
  readonly mount: HTMLElement;
  private readonly plugins: ((game: Game) => void | Promise<void>)[];
  private readonly moduleList: ModuleList | undefined;
  private moduleHost: ModuleHost | undefined;
  private readonly steps: FixedStep;
  private blurred = false;
  private switching: Promise<void> = Promise.resolve();
  private globalObjectsLoaded: Promise<void> | undefined;
  private readonly transitionLayer = new PixiContainer();
  private loadingLayer: PixiContainer | undefined;
  private safeProbe: HTMLElement | undefined;

  constructor(config: ResolvedGameConfig, options: CreateGameOptions) {
    this.config = config;
    this.scenes = options.scenes;
    this.registry = options.objects ?? { global: {}, scenes: {} };
    this.mount = options.mount;
    this.plugins = options.plugins ?? [];
    this.moduleList = options.modules;
    this.platform = new WebPlatform(config.id);
    this.steps = new FixedStep(config.tickRate);
    this.settings = new Settings(`blacklight:${config.id}:settings`);
    this.assets = new AssetStore(options.assets);
    this.sheets = new SheetCache(this.assets);
    this.input = new InputManager(config.input, this.settings);
    this.audio = new AudioManager(this.assets, this.settings);
    this.random = new Random(config.seed ?? Date.now());
    this.time = { step: 0, now: 0, dt: 1 / config.tickRate, scale: 1 };
    this.release = options.release ?? false;
    this.save = new SaveManager(this);
    this.security = new SecurityRuntime(this, resolveSecurity(config.security, this.release));
  }

  /**
   * Listens to a game event; same as `game.events.on`.
   *
   * @example
   * ```ts
   * game.on('tamper', (event) => { report(event.kind); event.restore(); });
   * ```
   */
  on<K extends keyof GameEvents>(name: K, listener: (payload: GameEvents[K]) => void): () => void {
    return this.events.on(name, listener);
  }

  /** @internal Called by {@link createGame}. */
  async start(): Promise<void> {
    const { resolution } = this.config;
    if (resolution.pixelArt) TextureStyle.defaultOptions.scaleMode = 'nearest';
    await this.app.init({
      background: '#000000',
      antialias: !resolution.pixelArt,
      autoDensity: true,
      resolution: globalThis.devicePixelRatio || 1,
      roundPixels: resolution.pixelArt,
    });
    Object.assign(this.mount.style, {
      display: 'grid',
      placeItems: 'center',
      overflow: 'hidden',
      background: '#000',
    });
    document.title = this.config.name;
    this.app.canvas.style.display = 'block';
    this.mount.append(this.app.canvas);
    this.app.stage.addChild(this.world, this.transitionLayer);
    this.layout();
    new ResizeObserver(() => this.layout()).observe(this.mount);
    matchMedia(`(resolution: ${globalThis.devicePixelRatio}dppx)`).addEventListener?.(
      'change',
      () => this.layout(),
    );

    this.input.attach(this.app.canvas, (x, y) => this.toVirtual(x, y));
    this.audio.attach();
    if (this.config.pauseOnBlur) {
      document.addEventListener('visibilitychange', () => this.setBlurred(document.hidden));
      window.addEventListener('blur', () => this.setBlurred(true));
      window.addEventListener('focus', () => this.setBlurred(false));
    }

    // Fonts in assets/ are available to every scene from the start.
    await this.assets.load(
      this.assets.paths.filter(
        (p) =>
          p.startsWith('assets/') &&
          (FONT_EXTENSIONS.includes(extension(p)) || extension(p) === 'fnt'),
      ),
    );

    this.app.ticker.add((ticker) => this.events.emit('frame', { deltaMS: ticker.deltaMS }));
    this.app.ticker.add((ticker) => {
      if (!this.paused && !this.blurred) {
        this.draw(this.steps.advance(ticker.deltaMS * this.time.scale, () => this.tick()));
      } else {
        this.draw(1);
      }
    });

    for (const plugin of this.plugins) await plugin(this);
    this.security.start();
    // After the plugins, which may replace `platform`; before the first scene, which may use modules.
    this.moduleHost = new ModuleHost(this);
    await this.moduleHost.install(this.moduleList ?? { definitions: [] });
    this.mount.dataset.blacklightState = 'loading';
    await this.goto(this.config.entry as SceneName);
    this.mount.dataset.blacklightState = 'running';
    // NF-02: a user timing mark once the entry scene's first frame is rendered (after Pixi's
    // render, which runs at LOW priority). Cold-start measurements read it from a trace, since a
    // packaged release app accepts no debugger; it also shows in DevTools' Performance panel.
    this.app.ticker.addOnce(
      () => performance.mark('blacklight:interactive'),
      undefined,
      UPDATE_PRIORITY.UTILITY,
    );
  }

  /** Scenes that receive steps: the current scene unless an overlay pauses it, and the overlays. */
  private get active(): Scene<never>[] {
    const list: Scene<never>[] = [];
    const pausedBelow = this.overlays.findLastIndex((o) => o.pauseBelow);
    if (this.scene && pausedBelow < 0) list.push(this.scene);
    this.overlays.forEach((o, i) => {
      if (i >= pausedBelow) list.push(o.scene);
    });
    return list;
  }

  private tick(): void {
    this.input.update();
    for (const scene of this.active) scene.step(this.time.dt);
    this.time.step++;
    this.time.now += this.time.dt * 1000;
    this.events.emit('step', { step: this.time.step });
  }

  private draw(alpha: number): void {
    this.scene?.draw(alpha);
    for (const { scene } of this.overlays) scene.draw(alpha);
  }

  /** Stops the game: disposes the modules (last set up first), then the renderer. */
  async destroy(): Promise<void> {
    await this.moduleHost?.dispose();
    this.app.destroy(true, { children: true });
  }

  /** Pauses the game logic (the display keeps updating). */
  pause(): void {
    if (this.paused) return;
    this.paused = true;
    // Menus keep their sounds while paused: only game buses go quiet.
    this.audio.setPaused(true, { ui: true });
    this.events.emit('pause');
  }

  resume(): void {
    if (!this.paused) return;
    this.paused = false;
    this.steps.reset();
    this.audio.setPaused(false, { ui: true });
    this.events.emit('resume');
  }

  /**
   * Runs `count` fixed steps now and draws, whatever the pause state: step-by-step debugging and
   * deterministic tests.
   */
  step(count = 1): void {
    for (let i = 0; i < count; i++) this.tick();
    this.draw(1);
  }

  /** Converts a client (CSS) position to virtual pixels of the design area. */
  toVirtual(clientX: number, clientY: number): { x: number; y: number } {
    const rect = this.app.canvas.getBoundingClientRect();
    const v = this.viewport;
    return {
      x: (clientX - rect.left - v.originX) / v.scale,
      y: (clientY - rect.top - v.originY) / v.scale,
    };
  }

  /** Scene names known to the game. */
  get sceneNames(): string[] {
    return Object.keys(this.scenes);
  }

  /**
   * Stops the current scene (and overlays) and starts `name`. Calls made while a switch is in
   * progress run after it.
   *
   * @throws Error when no scene has that name, with the closest names.
   */
  goto(name: SceneName, params?: unknown, options: GotoOptions = {}): Promise<void> {
    this.switching = this.switching.then(() => this.switchTo(name, params, options));
    return this.switching;
  }

  /** Loads a scene's code and files ahead of time so `goto` starts it at once. */
  async preload(name: SceneName): Promise<void> {
    await this.prepare(name, () => {});
  }

  /**
   * Opens a scene over the current one (pause menu, dialogs). With `pauseBelow` (the default)
   * the scenes under it stop updating.
   */
  async overlay(
    name: SceneName,
    params?: unknown,
    options: { pauseBelow?: boolean } = {},
  ): Promise<Scene<never>> {
    const scene = await this.instantiate(name);
    this.world.addChild(scene.stage);
    this.overlays.push({ scene, pauseBelow: options.pauseBelow ?? true });
    await scene.start(params);
    return scene;
  }

  /** Closes an overlay (the top one by default). */
  closeOverlay(scene?: Scene<never>): void {
    const index = scene
      ? this.overlays.findIndex((o) => o.scene === scene)
      : this.overlays.length - 1;
    const entry = this.overlays[index];
    if (!entry) return;
    this.overlays.splice(index, 1);
    entry.scene.dispose();
  }

  private async switchTo(name: SceneName, params: unknown, options: GotoOptions): Promise<void> {
    const transition = this.resolveTransition(options.transition);
    if (transition && this.scene) await this.runTransition(transition, 0, 1);

    const scene = await this.instantiate(name);
    while (this.overlays.length > 0) this.closeOverlay();
    const previous = this.scene;
    if (previous) {
      this.scene = undefined;
      previous.dispose();
    }
    this.world.addChildAt(scene.stage, 0);
    await scene.start(params);
    this.steps.reset();
    this.scene = scene;
    this.mount.dataset.blacklightScene = name;
    this.events.emit('scene', { name });
    if (transition) await this.runTransition(transition, 1, 0);
  }

  private resolveTransition(transition: GotoOptions['transition']): Transition | undefined {
    if (!transition || transition === 'none') return undefined;
    if (typeof transition !== 'string') return transition;
    const found = this.transitions.get(transition);
    if (!found) {
      const known = [...this.transitions.keys()];
      throw new Error(
        `Unknown scene transition "${transition}".${didYouMean(transition, known)} Known: none, ${known.join(', ')}. Register one with game.transitions.set(name, transition).`,
      );
    }
    return found;
  }

  /** @internal Loads a scene and creates it (without starting it). */
  async instantiate(name: SceneName): Promise<Scene<never>> {
    const SceneClass = await this.prepare(name, (progress) => this.showLoading(name, progress));
    this.hideLoading();
    const scene = new (SceneClass as unknown as new () => Scene<never>)();
    scene.init(this, name);
    return scene;
  }

  /** Loads the scene module, its objects and its files. */
  private async prepare(
    name: string,
    onProgress: (progress: number) => void,
  ): Promise<typeof Scene> {
    const load = this.scenes[name];
    if (!load) {
      const known = this.sceneNames;
      throw new Error(
        `Unknown scene "${name}".${didYouMean(name, known)} Scenes live in scenes/<name>/<name>.scene.ts; known scenes: ${known.join(', ') || 'none'}.`,
      );
    }
    const { default: SceneClass } = await load();
    if (typeof SceneClass !== 'function' || !(SceneClass.prototype instanceof Scene)) {
      throw new Error(
        `scenes/${name}/${name}.scene.ts must default-export a class: \`export default class ... extends Scene\`.`,
      );
    }
    const classes = await this.loadObjects(name);
    const files = Scene.assetPaths(SceneClass as unknown as typeof Scene, name, this.assets.paths);
    const total = classes.length + 1;
    let done = 0;
    const tick = () => onProgress(++done / total);
    await Promise.all([
      this.assets.load(files).then(tick),
      ...classes.map((type) => this.sheets.preload(type).then(tick)),
    ]);
    return SceneClass as unknown as typeof Scene;
  }

  /** Loads global objects (once) and the scene's own objects; returns every class it can spawn. */
  private async loadObjects(sceneName: string): Promise<(typeof GameObject)[]> {
    this.globalObjectsLoaded ??= Promise.all(
      Object.entries(this.registry.global).map(async ([name, entry]) => {
        const { default: type } = await entry.load();
        this.checkObjectModule(type, entry.path);
        stamp(type, name, entry.path);
        this.classes.set(name, type);
      }),
    ).then(() => undefined);
    await this.globalObjectsLoaded;
    let local = this.sceneClasses.get(sceneName);
    if (!local) {
      local = new Map();
      for (const [name, entry] of Object.entries(this.registry.scenes[sceneName] ?? {})) {
        const { default: type } = await entry.load();
        this.checkObjectModule(type, entry.path);
        stamp(type, name, entry.path);
        local.set(name, type);
      }
      this.sceneClasses.set(sceneName, local);
    }
    return [...new Set([...this.classes.values(), ...local.values()])];
  }

  private checkObjectModule(type: unknown, path: string): void {
    if (typeof type !== 'function') {
      const name = path.slice(path.lastIndexOf('/') + 1);
      throw new Error(
        `${path}/${name}.object.ts must default-export a class: \`export default class ... extends Sprite\`.`,
      );
    }
  }

  /** @internal Hot reload: later loads of scene `name` use `type`. */
  replaceScene(name: string, type: typeof Scene): void {
    this.scenes[name] = async () => ({ default: type as unknown as SceneClass });
  }

  /**
   * @internal Hot reload: the object registered as `name` (in `sceneName` when scene-local)
   * becomes `type`. Returns the class it replaces.
   */
  replaceObject(
    name: string,
    type: typeof GameObject,
    sceneName?: string,
  ): typeof GameObject | undefined {
    const map = sceneName ? this.sceneClasses.get(sceneName) : this.classes;
    const previous = map?.get(name);
    map?.set(name, type);
    // The module loader would return the first version from the browser's module cache.
    const entry = sceneName ? this.registry.scenes[sceneName]?.[name] : this.registry.global[name];
    if (entry) entry.load = async () => ({ default: type as GameObjectClass });
    return previous;
  }

  /** @internal Remembers classes spawned directly, so snapshots can re-create them by name. */
  rememberClass(type: typeof GameObject): void {
    const name = nameOf(type);
    if (!this.classes.has(name)) this.classes.set(name, type);
  }

  /**
   * Class registered under `name`: the scene's own objects first, then global ones.
   * @throws Error with the closest names when it does not exist.
   */
  objectClass(name: string, sceneName?: string): GameObjectClass {
    const type =
      (sceneName && this.sceneClasses.get(sceneName)?.get(name)) || this.classes.get(name);
    if (!type) {
      const known = [
        ...this.classes.keys(),
        ...(sceneName ? (this.sceneClasses.get(sceneName)?.keys() ?? []) : []),
      ];
      throw new Error(
        `Unknown object "${name}".${didYouMean(name, known)} Objects live in objects/<name>/<name>.object.ts or scenes/<scene>/objects/<name>/.`,
      );
    }
    return type as GameObjectClass;
  }

  private async runTransition(transition: Transition, from: number, to: number): Promise<void> {
    const size = { width: this.config.resolution.width, height: this.config.resolution.height };
    this.transitionLayer.position.copyFrom(this.world.position);
    this.transitionLayer.scale.copyFrom(this.world.scale);
    const start = performance.now();
    await new Promise<void>((resolve) => {
      const frame = () => {
        const t = Math.min(1, (performance.now() - start) / transition.duration);
        transition.draw(this.transitionLayer, from + (to - from) * t, size);
        if (t < 1) requestAnimationFrame(frame);
        else resolve();
      };
      frame();
    });
    if (to === 0) for (const child of this.transitionLayer.removeChildren()) child.destroy();
  }

  private showLoading(scene: string, progress: number): void {
    this.events.emit('loading', { scene, progress });
    if (!this.loadingLayer) {
      this.loadingLayer = new PixiContainer();
      this.app.stage.addChild(this.loadingLayer);
    }
    this.loadingLayer.position.copyFrom(this.world.position);
    this.loadingLayer.scale.copyFrom(this.world.scale);
    this.loadingScreen.draw(this.loadingLayer, progress, {
      width: this.config.resolution.width,
      height: this.config.resolution.height,
    });
  }

  private hideLoading(): void {
    this.loadingLayer?.destroy({ children: true });
    this.loadingLayer = undefined;
  }

  private setBlurred(blurred: boolean): void {
    if (this.blurred === blurred) return;
    this.blurred = blurred;
    if (blurred) this.input.releaseAll();
    else this.steps.reset();
    if (!this.paused) this.audio.setPaused(blurred);
  }

  private layout(): void {
    const { clientWidth, clientHeight } = this.mount;
    if (clientWidth === 0 || clientHeight === 0) return;
    this.viewport = computeViewport(clientWidth, clientHeight, this.config.resolution);
    const { canvasWidth, canvasHeight, scale, originX, originY } = this.viewport;
    this.app.renderer.resolution = globalThis.devicePixelRatio || 1;
    this.app.renderer.resize(canvasWidth, canvasHeight);
    this.world.scale.set(scale);
    this.world.position.set(originX, originY);
    this.textResolution = Math.min(4, Math.max(1, scale * this.app.renderer.resolution));
    this.safeArea = this.readSafeArea();
    this.events.emit('resize', { viewport: this.viewport });
    for (const scene of [this.scene, ...this.overlays.map((o) => o.scene)]) {
      for (const object of scene?.objects ?? []) {
        if (object instanceof Text) object.setScreenResolution(this.textResolution);
      }
    }
  }

  /** Safe area from the CSS `env(safe-area-inset-*)` values, in virtual pixels. */
  private readSafeArea(): Rect {
    if (!this.safeProbe) {
      this.safeProbe = document.createElement('div');
      this.safeProbe.style.cssText =
        'position:fixed;visibility:hidden;pointer-events:none;padding:env(safe-area-inset-top,0px) env(safe-area-inset-right,0px) env(safe-area-inset-bottom,0px) env(safe-area-inset-left,0px)';
      document.body.append(this.safeProbe);
    }
    const style = getComputedStyle(this.safeProbe);
    const v = this.viewport;
    const canvas = this.app.canvas.getBoundingClientRect();
    const left = Math.max(0, parseFloat(style.paddingLeft) - canvas.left);
    const top = Math.max(0, parseFloat(style.paddingTop) - canvas.top);
    const right = Math.max(0, parseFloat(style.paddingRight) - (innerWidth - canvas.right));
    const bottom = Math.max(0, parseFloat(style.paddingBottom) - (innerHeight - canvas.bottom));
    return {
      x: (left - v.originX) / v.scale,
      y: (top - v.originY) / v.scale,
      width: (v.canvasWidth - left - right) / v.scale,
      height: (v.canvasHeight - top - bottom) / v.scale,
    };
  }
}

/**
 * Validates the configuration, creates the renderer inside `mount` and starts the entry scene.
 * The CLI generates the call; games rarely call it themselves.
 *
 * @example
 * ```ts
 * const game = await createGame(config, {
 *   scenes: scenesFromGlob(import.meta.glob('./scenes/*\/*.scene.ts')),
 *   mount: document.getElementById('game')!,
 * });
 * ```
 */
export async function createGame(config: GameConfig, options: CreateGameOptions): Promise<Game> {
  const resolved = resolveConfig(config);
  if (!options.scenes[resolved.entry]) {
    const known = Object.keys(options.scenes);
    throw new Error(
      `The entry scene "${resolved.entry}" from game.config.ts does not exist.${didYouMean(resolved.entry, known)} Create scenes/${resolved.entry}/${resolved.entry}.scene.ts or change \`entry\`.`,
    );
  }
  const game = new Game(resolved, options);
  await game.start();
  return game;
}
